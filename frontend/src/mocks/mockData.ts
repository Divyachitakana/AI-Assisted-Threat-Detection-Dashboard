const SEVERITY_WEIGHTS: Record<Severity, number> = {
  critical: 6,
  high: 16,
  medium: 34,
  low: 32,
  info: 12,
};

const STATUS_WEIGHTS: Record<IncidentStatus, number> = {
  open: 22,
  investigating: 28,
  contained: 15,
  resolved: 30,
  false_positive: 5,
};

const PRIORITY_BY_SEVERITY: Record<Severity, AlertPriority> = {
  critical: "p1",
  high: "p2",
  medium: "p3",
  low: "p4",
  info: "p4",
};

const DATA_SOURCES = [
  "cloud_audit_logs",
  "vpc_flow_logs",
  "security_command_center",
  "external_threat_intel",
] as const;

function buildAlert(n: number): Alert {
  const template = pick(THREAT_TEMPLATES);
  const severity = pickWeighted(SEVERITY_WEIGHTS);
  const mitre = mitreForTemplate(template);
  const detectedAt = randomPastTimestamp(24 * 14);
  const includeCve = ["Exploit", "Malware", "Web Attack"].includes(template.category) && randInt(0, 1) === 1;

  return {
    id: id("ALT", n),
    title: template.name,
    description: `${template.name} detected on ${pick(ASSET_NAMES).name}. Confidence and risk scoring generated by the anomaly detection and classification engine.`,
    severity,
    status: pickWeighted(STATUS_WEIGHTS),
    source: pick(DATA_SOURCES),
    mitreTactic: `${mitre.tacticName} (${mitre.tacticId})`,
    mitreTechniqueId: mitre.techniqueId,
    confidenceScore: randInt(58, 99),
    riskScore: randInt(10, 98),
    assetId: pick(ASSET_NAMES).name,
    sourceIp: randomIp(),
    destinationIp: randomInternalIp(),
    detectedAt,
    updatedAt: detectedAt,
    priority: PRIORITY_BY_SEVERITY[severity],
    assignedAnalyst: randInt(0, 3) > 0 ? pick(ANALYSTS) : undefined,
    cveId: includeCve ? randomCveId() : undefined,
    attackType: template.category,
  };
}

export const MOCK_ALERTS: Alert[] = Array.from({ length: 64 }, (_, i) => buildAlert(i + 1));

function buildIncidentTimeline(alert: Alert, status: IncidentStatus): IncidentTimelineEvent[] {
  const events: IncidentTimelineEvent[] = [
    {
      id: "evt-1",
      label: `Anomaly detected by ML engine (confidence ${alert.confidenceScore}%)`,
      actor: "system",
      timestamp: alert.detectedAt,
    },
    {
      id: "evt-2",
      label: "Incident auto-created and correlated with related alerts",
      actor: "system",
      timestamp: alert.detectedAt,
    },
  ];
  if (alert.assignedAnalyst) {
    events.push({
      id: "evt-3",
      label: `Assigned to ${alert.assignedAnalyst.name} for triage`,
      actor: "analyst",
      timestamp: alert.updatedAt,
    });
  }
  events.push({
    id: "evt-4",
    label: "Security Assistant suggested containment playbook based on MITRE ATT&CK mapping",
    actor: "ai_assistant",
    timestamp: alert.updatedAt,
    detail: `Recommended technique-specific response for ${alert.mitreTechniqueId}`,
  });
  if (status === "contained" || status === "resolved") {
    events.push({
      id: "evt-5",
      label: status === "resolved" ? "Incident marked resolved" : "Threat contained, monitoring for recurrence",
      actor: "analyst",
      timestamp: alert.updatedAt,
    });
  }
  return events;
}

function buildIncident(n: number, alert: Alert): Incident {
  const status = pickWeighted(STATUS_WEIGHTS);
  return {
    id: id("INC", n),
    alertIds: [alert.id],
    title: alert.title,
    severity: alert.severity,
    status,
    assignee: alert.assignedAnalyst?.name,
    riskScore: alert.riskScore,
    createdAt: alert.detectedAt,
    updatedAt: alert.updatedAt,
    timeline: buildIncidentTimeline(alert, status),
  };
}

