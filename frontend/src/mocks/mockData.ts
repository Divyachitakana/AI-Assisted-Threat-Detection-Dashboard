export const ATTACK_TREND: AttackTrendPoint[] = Array.from({ length: 30 }, (_, i) => {
  const date = new Date();
  date.setDate(date.getDate() - (29 - i));
  const base = 4 + Math.round(3 * Math.sin(i / 4));
  return {
    timestamp: date.toISOString().slice(0, 10),
    critical: Math.max(0, base - 3 + randInt(0, 2)),
    high: Math.max(0, base - 1 + randInt(0, 3)),
    medium: Math.max(0, base + 2 + randInt(0, 4)),
    low: Math.max(0, base + 4 + randInt(0, 5)),
  };
});

